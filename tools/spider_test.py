def hx(b): return " ".join("%02X" % x for x in b)

class Amp:
    def __init__(self, path):
        self.fd = os.open(path, os.O_RDWR | os.O_NONBLOCK)
        self.buf = bytearray()
    def send(self, data):
        view = memoryview(data)
        while view:
            select.select([], [self.fd], [], 1.0)
            try:
                n = os.write(self.fd, view)
            except BlockingIOError:
                continue
            view = view[n:]
    def drain(self, quiet=0.05, limit=1.0):
        """Read until the amp has been quiet for `quiet` seconds. Returns list of SysEx messages."""
        msgs, end, last = [], time.time() + limit, time.time()
        while time.time() < end and time.time() - last < quiet:
            r, _, _ = select.select([self.fd], [], [], 0.01)
            if r:
                try:
                    chunk = os.read(self.fd, 4096)
                except BlockingIOError:
                    continue
                if chunk:
                    last = time.time()
                    self.buf += chunk
            while 0xF7 in self.buf:
                i = self.buf.index(0xF7)
                msgs.append(bytes(self.buf[:i + 1]))
                del self.buf[:i + 1]
        return msgs

def drive_pair(seq, raw5):
    a = bytes.fromhex("f000010c22054d00") + bytes([seq, 0, 0, 0x07, 0, 0x0A, 0, 0, 0, 0x10]) + bytes(10) + b"\xf7"
    b = (bytes.fromhex("f000010c22054d00") + bytes([seq + 1, 0, 0, 0x0F, 0, 0x2A, 0, 0, 0, 0x25, 0, 0, 1, 0, 4, 0, 0, 0])
         + bytes.fromhex(raw5) + bytes(5) + b"\xf7")
    return a, b

def main():
    msgs = [bytes.fromhex(h) for h in HANDSHAKE]
    print("handshake messages:", len(msgs))
    if DRY:
        for w in ("low", "high"):
            a, b = drive_pair(0x0C, VALUES[w]); print(w, hx(a)); print(w, hx(b))
        return
    amp = Amp(DEV)
    amp.drain(0.1, 0.3)
    replies = 0
    for i, m in enumerate(msgs):
        amp.send(m)
        r = amp.drain()
        replies += len(r)
        if i < 3:
            for x in r: print("  reply to handshake %d: %s" % (i, hx(x)[:110]))
    print("handshake done, amp sent %d replies to %d messages" % (replies, len(msgs)))
    seq = 0x0C
    for w in (["low", "high"] if WHAT == "both" else [WHAT]):
        a, b = drive_pair(seq, VALUES[w]); seq += 2
        print("sending Drive", w)
        amp.send(a); ra = amp.drain()
        amp.send(b); rb = amp.drain()
        for x in ra + rb: print("  amp replied:", hx(x))
        if not (ra or rb): print("  (no reply)")
        input("  Drive set to %s. Check the sound / app, then press Enter..." % w)

if __name__ == "__main__":
    main()
